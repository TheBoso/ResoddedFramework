"""Generates src/Lawn/Component/EnumNames.generated.cpp: the value names of the game's enums, so definition files
(assets/definitions) can say "ZOMBIE_FOOTBALL" or "HELMTYPE_PAIL" instead of numbers.

Run it from anywhere after adding or changing enum values:

    python tools/generate_enum_names.py

Only enums declared at file scope are picked up. An enum whose values can't be worked out (an initializer this
script doesn't understand) is skipped with a warning; it then reads and writes as numbers.
"""

import glob
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SRC = os.path.join(ROOT, 'src')
OUTPUT = os.path.join(SRC, 'Lawn', 'Component', 'EnumNames.generated.cpp')

# Headers to scan, relative to src/, and the include the generated file uses for them
HEADERS = [
    ('ConstEnums.h', '../../ConstEnums.h'),
    ('Resources.h', '../../Resources.h'),
    ('Sexy.TodLib/TodFoley.h', '../../Sexy.TodLib/TodFoley.h'),
    ('Sexy.TodLib/Trail.h', '../../Sexy.TodLib/Trail.h'),
    ('Lawn/Plant.h', '../Plant.h'),
] + [('Lawn/Component/' + os.path.basename(p), os.path.basename(p))
     for p in sorted(glob.glob(os.path.join(SRC, 'Lawn', 'Component', '*.h')))]

# Enums not worth naming (internal bookkeeping)
SKIP = {'EntityKind'}

ENUM_RE = re.compile(r'\benum\s+(class\s+)?([A-Za-z_]\w*)\s*(?::\s*[\w:]+\s*)?\{')


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', text)


NAMESPACE_RE = re.compile(r'\bnamespace\s+(\w+)\s*\{')


def file_scope_enums(text):
    """(qualified name, is_class, body) of the enums declared outside any class or function (namespaces are fine)"""
    found = []
    namespaces = []
    depth = 0  # braces other than namespaces
    i = 0
    while i < len(text):
        if depth == 0:
            m = NAMESPACE_RE.match(text, i)
            if m:
                namespaces.append(m.group(1))
                i = m.end()
                continue
            m = ENUM_RE.match(text, i)
            if m:
                end = text.index('}', m.end())
                found.append(('::'.join(namespaces + [m.group(2)]), bool(m.group(1)), text[m.end():end]))
                i = end + 1
                continue
        c = text[i]
        if c == '{':
            depth += 1
        elif c == '}':
            if depth == 0 and namespaces:
                namespaces.pop()
            else:
                depth -= 1
        i += 1
    return found


def evaluate(body):
    """[(name, value)] or None when an initializer can't be evaluated"""
    values = []
    known = {}
    next_value = 0
    for item in body.split(','):
        item = item.strip()
        if not item or item.startswith('#'):
            continue
        if '=' in item:
            name, expr = (x.strip() for x in item.split('=', 1))
            expr = re.sub(r'\b\w+::', '', expr)  # Foo::BAR -> BAR
            expr = re.sub(r'(?<=\d)[uUlL]+\b', '', expr)
            if not re.fullmatch(r'[\w\s()+\-*/<>|&~^]+', expr):
                return None
            try:
                value = int(eval(expr, {'__builtins__': {}}, known))
            except Exception:
                return None
        else:
            name, value = item, next_value
        if not re.fullmatch(r'[A-Za-z_]\w*', name):
            return None
        values.append((name, value))
        known[name] = value
        next_value = value + 1
    return values


def main():
    includes = []
    tables = []
    registrations = []
    seen = set()
    for header, include in HEADERS:
        with open(os.path.join(SRC, header), encoding='utf-8', errors='replace') as f:
            text = strip_comments(f.read())
        used = False
        for name, is_class, body in file_scope_enums(text):
            if name in SKIP or name in seen:
                continue
            values = evaluate(body)
            if values is None:
                print('warning: skipped %s in %s (initializer not understood)' % (name, header))
                continue
            if not values:
                continue
            seen.add(name)
            used = True
            entries = ',\n'.join('\t{"%s", %d}' % (n, v) for n, v in values)
            table = 'k%sNames' % name.replace('::', '_')
            tables.append('static const EnumNameEntry %s[] = {\n%s,\n};' % (table, entries))
            registrations.append('\tEnumNames::Register(EnumKey<%s>(), "%s", %s, std::size(%s));'
                                 % (name, name.split('::')[-1], table, table))
        if used:
            includes.append('#include "%s"' % include)

    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/generate_enum_names.py - do not edit, rerun the script instead.\n\n')
        f.write('#include <iterator>\n#include "EnumNames.h"\n')
        f.write('\n'.join(includes) + '\n\n')
        f.write('\n\n'.join(tables) + '\n\n')
        f.write('static const bool gEnumNamesRegistered = []\n{\n')
        f.write('\n'.join(registrations) + '\n')
        f.write('\treturn true;\n}();\n')
    print('wrote %s (%d enums)' % (os.path.relpath(OUTPUT, ROOT), len(registrations)))


if __name__ == '__main__':
    main()
